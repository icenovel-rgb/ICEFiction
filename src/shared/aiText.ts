/**
 * AI가 준 글을 이 앱의 문단 규칙에 맞춘다(BLUEPRINT §8.1).
 *
 * 대부분의 글쓰기 도구는 문단을 **빈 줄**로 나눈다. 그런데 이 앱은 마크다운 한 줄이 곧 한 문단이고,
 * 문단 사이는 줄 아래 여백(`--paper-para-gap`)으로 벌린다. 그래서 AI가 관례대로 빈 줄을 넣으면
 * 간격이 두 겹으로 붙어 원고가 두 배로 벌어진다 — 사용자가 직접 쓸 때는 엔터 한 번이니 어긋난다.
 *
 * 종이에 비유하면 이렇다. 이 앱의 원고지는 줄마다 아래 여백이 이미 인쇄돼 있다. 거기에 한 줄을
 * 통째로 비우면 여백이 두 칸이 된다. AI가 준 글에서 그 빈 줄만 걷어내면 손으로 쓴 글과 같아진다.
 *
 * 이 파일은 **순수 함수만** 담는다(§11). 어디에 적용할지(고스트·본문에 넣기)는 부르는 쪽이 정한다.
 */

/** 코드 펜스 여닫이(``` 또는 ~~~) — 이 안에서는 빈 줄이 뜻을 갖는다. */
const FENCE = /^\s*(?:```|~~~)/

/**
 * 빈 줄(문단 구분)을 **줄바꿈 한 번**으로 줄인다.
 *
 * 지키는 것:
 *  · 줄 끝 공백 두 칸(Shift+Enter 하드 브레이크)은 건드리지 않는다 — 줄 자체를 지우지 않으므로.
 *  · 코드 펜스 안의 빈 줄은 그대로 둔다.
 *  · 멱등이다 — 스트리밍 중 누적본에 매번 적용해도 결과가 같다.
 *
 * 한계: GFM 표는 문단 바로 아래에서 시작하면 표로 읽히지 않는다(빈 줄이 필요한 유일한 문법).
 * 소설 원고에서 표를 쓰는 일이 없어 감수한다 — 필요하면 코드 펜스처럼 예외를 추가하면 된다.
 */
export function collapseBlankLines(text: string): string {
  const lines = String(text ?? '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
  const out: string[] = []
  let inFence = false
  for (const line of lines) {
    if (FENCE.test(line)) {
      inFence = !inFence
      out.push(line)
    } else if (inFence || line.trim() !== '') {
      out.push(line)
    }
    // 펜스 밖의 빈 줄은 버린다 — 문단 간격은 앱이 준다.
  }
  return out.join('\n')
}
